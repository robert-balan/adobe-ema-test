/**
 * The renderer, and in particular the nav surgery.
 *
 * The surgery is the risky part: it locates the brand strip the same way the implementation does
 * — by content shape, not by class, because AC-11 defines the carousel as "a strip of 2+ image-only
 * links" and nothing in the markup names it. Getting that wrong silently produces a fixture that
 * tests something other than what it claims, so it is pinned against a captured nav sample rather
 * than exercised against the client's live content.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import {
  metadataBlock, block, document_, fixturePage, findBrandStrip, editLink, transformNav,
} from '../lib/da-render.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const NAV = readFileSync(join(HERE, 'fixtures', 'nav-sample.html'), 'utf8');
const countLinks = (s) => (s.match(/<a\b[^>]*>\s*<picture>/g) || []).length;

/* -------------------------------------------------------------- primitives */

test('metadataBlock: key/value rows in DA shape', () => {
  const out = metadataBlock({ nav: '/drafts/qa/brands/nav-happy', Language: 'ar-MA' });
  assert.match(out, /<div class="metadata">/);
  assert.match(out, /<div><div><p>nav<\/p><\/div><div><p>\/drafts\/qa\/brands\/nav-happy<\/p><\/div><\/div>/);
  assert.match(out, /<p>Language<\/p><\/div><div><p>ar-MA<\/p>/);
});

test('metadataBlock: escapes values rather than emitting raw markup', () => {
  assert.match(metadataBlock({ Title: 'Sauces & <b>Condiments</b>' }), /Sauces &amp; &lt;b&gt;Condiments/);
});

test('block: variants are extra class tokens, rows and cells nest', () => {
  const out = block({ name: 'feature-grid', variants: ['columns-4', 'plain'], rows: [['<p>a</p>', '<p>b</p>']] });
  assert.match(out, /<div class="feature-grid columns-4 plain">/);
  assert.match(out, /<div><div><p>a<\/p><\/div><div><p>b<\/p><\/div><\/div>/);
});

test('document_: header, main with a div per section, footer', () => {
  const out = document_({ sections: ['<h2>One</h2>', '<h2>Two</h2>'] });
  assert.match(out, /^<body>\n<header><\/header>\n<main>/);
  assert.match(out, /<\/main>\n<footer><\/footer>\n<\/body>$/);
  assert.equal((out.match(/<div>\n<h2>/g) || []).length, 2);
});

test('fixturePage: identifies itself and carries its metadata', () => {
  const out = fixturePage({
    id: 'BRANDS-FX-01',
    title: 'Happy path',
    purpose: '8 logos',
    metadata: { nav: '/drafts/qa/brands/nav-happy' },
  }, { source: '/nav' });
  assert.match(out, /QA fixture — BRANDS-FX-01/);
  assert.match(out, /Generated by da-fixture\.mjs from \/nav/);
  assert.match(out, /Do not edit by hand/);
  assert.match(out, /<div class="metadata">/);
});

/* ------------------------------------------------------------ finding it */

test('findBrandStrip: finds the run of consecutive image-only links', () => {
  const strip = findBrandStrip(NAV);
  assert.ok(strip, 'a strip should be found');
  assert.equal(strip.links.length, 4);
  assert.match(strip.links[0], /alt="Alpha"/);
});

test('findBrandStrip: a single image link is not a strip', () => {
  const one = '<div><a href="/x"><picture><img src="a.png" alt="A"></picture></a></div>';
  assert.equal(findBrandStrip(one), null);
});

// A captioned link is still an <a><picture>, so the run is found — but the block classifies it as
// featured products. The fixture's job is to produce that input, not to judge it.
test('findBrandStrip: text between links breaks the run', () => {
  const split = NAV.replace('alt="Beta">\n</picture>\n</a>', 'alt="Beta">\n</picture>\n</a>\n<p>interrupting copy</p>');
  const strip = findBrandStrip(split);
  assert.ok(strip.links.length < 4, 'the run should be broken by intervening content');
});

/* ---------------------------------------------------------- editing links */

test('editLink: replaces alt and image source, and can add a caption', () => {
  const [first] = findBrandStrip(NAV).links;
  const edited = editLink(first, { alt: 'Renamed', src: 'https://example.test/broken.png', caption: 'A caption' });
  assert.match(edited, /alt="Renamed"/);
  assert.match(edited, /src="https:\/\/example\.test\/broken\.png"/);
  assert.match(edited, /srcset="https:\/\/example\.test\/broken\.png"/);
  assert.match(edited, /<p>A caption<\/p>/);
});

/* ------------------------------------------------------------- transform */

test('transformNav: grows the strip by cycling the available logos', () => {
  const out = transformNav(NAV, { count: 8 });
  assert.equal(countLinks(out), 8 + 0, 'eight brand links');
  assert.match(out, /Recipes/, 'the rest of the nav is untouched');
  assert.match(out, /Our brands:/, 'the label survives');
});

test('transformNav: shrinks the strip', () => {
  assert.equal(countLinks(transformNav(NAV, { count: 2 })), 2);
  assert.equal(countLinks(transformNav(NAV, { count: 1 })), 1);
});

test('transformNav: per-link overrides land on the right links', () => {
  const out = transformNav(NAV, {
    count: 3,
    links: [{}, { alt: 'Broken brand', src: 'https://example.test/missing.png' }, {}],
  });
  assert.match(out, /alt="Broken brand"/);
  assert.match(out, /example\.test\/missing\.png/);
  assert.equal(countLinks(out), 3);
});

test('transformNav: captions turn the strip into the featured-products case', () => {
  const out = transformNav(NAV, { count: 2, links: [{ caption: 'Knorr range' }, { caption: 'Hellmann\'s range' }] });
  assert.match(out, /<p>Knorr range<\/p>/);
  assert.match(out, /Hellmann&#x27;s range|Hellmann's range/);
});

test('transformNav: replaces or removes the label', () => {
  assert.match(transformNav(NAV, { count: 2, label: 'Unsere Marken:' }), /Unsere Marken:/);
  const bare = transformNav(NAV, { count: 2, removeLabel: true });
  assert.doesNotMatch(bare, /Our brands:/);
  assert.equal(countLinks(bare), 2, 'removing the label does not disturb the links');
});

test('transformNav: refuses a source with no strip rather than producing a silent dud', () => {
  assert.throws(() => transformNav('<body><main><div><p>nothing here</p></div></main></body>'),
    /no brand strip found/);
});
